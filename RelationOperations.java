public class RelationOperations {
    public static void main(String[] args) {
        int x = 6;
        int y = 5;
        int z = 6;

        boolean isXGreaterThanY = x > y;
        boolean isXLessThanY = x < y;
        boolean isXEquatToZ = x == z;
        boolean isXEqualToY = x == y;

        System.out.println("x greater than y : " + isXGreaterThanY);
        System.out.println("x less than y : " + isXLessThanY);
        System.out.println("x equal to z : " + isXEquatToZ);
        System.out.println("x equal to y : " + isXEqualToY);

    }

}
