public class Literal {
    public static void main(String[] args) {
        // LITERALS

        int num1 = 0b101; // 5
        int num2 = 0x7E; // 126
        int num3 = 10_00_00_000;

        // double
        double dob1 = 12e10;

        // boolean
        boolean bool = false; // you should not assign 0 or 1 to boolean data type

        // char

        char c = 'a';
        c++;

        System.out.println(c);// b
    }

}
